#!/usr/bin/env node
// Writes .env.local for the apps from the running local Supabase.
// Usage: npm run setup:env   (after npm run db:start)

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Builds the browser-safe env file from `supabase status -o json` output.
 * Only the public URL and publishable/anon key are written. Admin keys never are.
 * @param {Record<string, string | undefined>} status
 * @returns {string}
 */
export function buildEnvFile(status) {
  const url = status.API_URL;
  const key = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
  if (!url || !key) {
    throw new Error('Local Supabase is not running. Start it first with: npm run db:start');
  }
  return [
    '# Generated by npm run setup:env. Local development only, safe to regenerate.',
    `VITE_SUPABASE_URL=${url}`,
    `VITE_SUPABASE_ANON_KEY=${key}`,
    '',
  ].join('\n');
}

function main() {
  let status;
  try {
    status = JSON.parse(execSync('npx supabase status -o json', { encoding: 'utf8' }));
  } catch {
    status = {};
  }
  const contents = buildEnvFile(status);
  const target = fileURLToPath(new URL('../.env.local', import.meta.url));
  writeFileSync(target, contents);
  console.log('✔ Wrote .env.local. You can now run: npm run dev');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main();
  } catch (error) {
    console.error(`✘ ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
