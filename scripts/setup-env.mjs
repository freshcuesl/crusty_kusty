#!/usr/bin/env node
// Writes .env.local so the apps know which Supabase database to use.
//   npm run setup:env          → local Docker database (after npm run db:start)
//   npm run setup:env:cloud    → free cloud test project (asks for URL and publishable key)

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';

const HEADER = '# Generated by npm run setup:env. Safe to regenerate. Never put secret keys here.';

/**
 * Builds the browser-safe env file from `supabase status -o json` output.
 * Only the public URL and publishable/anon key are written. Admin keys never are.
 * @param {Record<string, string | undefined>} status
 * @returns {string}
 */
export function buildEnvFile(status) {
  const url = status.API_URL;
  const key = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
  if (!url || !key) {
    throw new Error('Local Supabase is not running. Start it first with: npm run db:start');
  }
  return [HEADER, `VITE_SUPABASE_URL=${url}`, `VITE_SUPABASE_ANON_KEY=${key}`, ''].join('\n');
}

/** @param {string} key */
function isSecretKey(key) {
  if (key.startsWith('sb_secret_')) return true;
  const payload = key.split('.')[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, 'base64url').toString('utf8')).role === 'service_role';
  } catch {
    return false;
  }
}

/**
 * Builds the env file for a hosted Supabase project from what the user pastes.
 * @param {{ url: string; key: string }} input
 * @returns {string}
 */
export function buildCloudEnvFile({ url, key }) {
  let parsed;
  try {
    parsed = new URL(url.trim());
  } catch {
    parsed = undefined;
  }
  if (!parsed || parsed.protocol !== 'https:' || !parsed.hostname.endsWith('.supabase.co')) {
    throw new Error('That is not a Supabase Project URL. It looks like https://abcd.supabase.co');
  }
  const cleanKey = key.trim();
  if (!cleanKey) throw new Error('Paste the publishable key (it starts with sb_publishable_).');
  if (isSecretKey(cleanKey)) {
    throw new Error('That is the secret key. Never share it. Copy the publishable key instead.');
  }
  return [
    HEADER,
    `VITE_SUPABASE_URL=${parsed.origin}`,
    `VITE_SUPABASE_ANON_KEY=${cleanKey}`,
    '',
  ].join('\n');
}

const TARGET = fileURLToPath(new URL('../.env.local', import.meta.url));

function local() {
  let status;
  try {
    status = JSON.parse(execSync('npx supabase status -o json', { encoding: 'utf8' }));
  } catch {
    status = {};
  }
  writeFileSync(TARGET, buildEnvFile(status));
}

async function cloud() {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  try {
    const url = await rl.question('Paste your Project URL, then press Enter: ');
    const key = await rl.question('Paste your publishable key, then press Enter: ');
    writeFileSync(TARGET, buildCloudEnvFile({ url, key }));
  } finally {
    rl.close();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const run = process.argv.includes('--cloud') ? cloud() : Promise.resolve(local());
  run.then(
    () => console.log('✔ Wrote .env.local. You can now run: npm run dev'),
    (error) => {
      console.error(`✘ ${error instanceof Error ? error.message : String(error)}`);
      process.exit(1);
    },
  );
}
